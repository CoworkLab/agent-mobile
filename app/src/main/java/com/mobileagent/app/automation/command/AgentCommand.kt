package com.mobileagent.app.automation.command

sealed class AgentCommand {
    data class PlayYouTube(val query: String) : AgentCommand()
    data class SearchYouTube(val query: String) : AgentCommand()
    data class OpenApp(val packageName: String) : AgentCommand()
    data class WhatsAppMessage(val contact: String, val message: String) : AgentCommand()
    data class WhatsAppCall(val contact: String, val video: Boolean) : AgentCommand()
    data class WhatsAppDeleteMessage(val contact: String?, val forEveryone: Boolean) : AgentCommand()
    object SubscribeChannel : AgentCommand()
    object ToggleFullscreen : AgentCommand()
    data class Brightness(val level: Int, val isRelative: Boolean = false, val delta: Int = 0) : AgentCommand()
    data class Volume(val level: Int, val isRelative: Boolean = false, val delta: Int = 0) : AgentCommand()
    data class Flash(val enabled: Boolean) : AgentCommand()
    data class Remember(val text: String) : AgentCommand()
    data class Forget(val query: String) : AgentCommand()
    object WhatDoYouRemember : AgentCommand()
    data class SearchWeb(val query: String) : AgentCommand()
    data class OpenWebUrls(val urls: List<String>) : AgentCommand()
    data class PhoneCall(val contactOrNumber: String) : AgentCommand()
    object PauseMedia : AgentCommand()
    object ResumeMedia : AgentCommand()
    object NextMedia : AgentCommand()
    object PreviousMedia : AgentCommand()
    data class ConfirmAction(val confirmed: Boolean) : AgentCommand()
    data class DisambiguationChoice(val choice: String) : AgentCommand()
    object RecallBirthday : AgentCommand()
    object RecallFavoriteSong : AgentCommand()
    object RecallRoutine : AgentCommand()
    object GoToBackground : AgentCommand()
}
